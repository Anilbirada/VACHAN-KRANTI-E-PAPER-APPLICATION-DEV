import express from 'express';
import cors from 'cors';
import helmet from 'helmet';
import morgan from 'morgan';
import rateLimit from 'express-rate-limit';
import dotenv from 'dotenv';
import path from 'node:path';
import routes from './routes.js';
import { pool } from './db.js';
dotenv.config();
const app=express();
app.disable('x-powered-by');
app.use(helmet({crossOriginResourcePolicy:{policy:'cross-origin'}}));
app.use(cors({origin:(process.env.CLIENT_ORIGIN||'http://localhost:5173').split(',').map(s=>s.trim()),credentials:false}));
app.use(express.json({limit:'2mb'}));
app.use(express.urlencoded({extended:true,limit:'2mb'}));
app.use(morgan('dev'));
app.use('/api/auth/login',rateLimit({windowMs:15*60*1000,max:30,standardHeaders:true,legacyHeaders:false}));
const uploadDir=path.resolve(process.env.UPLOAD_DIR||'uploads');
app.use('/uploads',express.static(uploadDir,{dotfiles:'deny',index:false,setHeaders:(res)=>res.setHeader('X-Content-Type-Options','nosniff')}));
app.get('/api/health',async(_req,res)=>{try{await pool.query('SELECT 1');res.json({ok:true,database:'connected',service:'vachana-kranti-api'});}catch{res.status(503).json({ok:false,database:'unavailable'});}});
app.use('/api',routes);
app.use((err,_req,res,_next)=>{console.error(err);if(err.code==='23505')return res.status(409).json({error:'A record with these details already exists'});if(err.code==='23503')return res.status(400).json({error:'This record is referenced by another record'});if(err.name==='MulterError')return res.status(400).json({error:err.message});res.status(500).json({error:err.message==='Only PDF, JPG, PNG and WEBP files are allowed'?err.message:'Unexpected server error'});});
const port=Number(process.env.PORT)||4000;
app.listen(port,()=>console.log(`Vachana Kranti API running on http://localhost:${port}`));
